"""Zernike polynomial basis used by the aperture-coefficient beam models.

The 66 polynomials (radial orders ``n = 0 .. 10``) are written in expanded
Cartesian form, in the exact order and normalisation used by the aperture
coefficient tables (Sekhar et al. 2022) shipped with AstroVIPER — ported
verbatim from SIRIUS ``_zernike_polynomials.py``.  They are **not** the
orthonormal Zernike polynomials (no ``sqrt(2 (n + 1))`` factors), so they must
not be regenerated from a generic Zernike library without re-validating the
coefficient tables.
"""

from __future__ import annotations

import numpy as np

N_ZERNIKE_TERMS = 66


def zernike_basis(x: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Evaluate the 66 Zernike basis polynomials on normalised aperture coordinates.

    Parameters
    ----------
    x, y : np.ndarray
        Aperture coordinates normalised to the dish radius (unit disc), any shape.

    Returns
    -------
    np.ndarray, [66, *x.shape]
        ``basis[i]`` is the ``i``-th polynomial ``P_i(x, y)``; comments give the
        azimuthal/radial orders ``(m, n)`` of each term.
    """
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)
    basis = np.empty((N_ZERNIKE_TERMS,) + x.shape, dtype=np.float64)
    basis[0] = np.ones_like(x)  # m = 0 n = 0
    basis[1] = x  # m = -1 n = 1
    basis[2] = y  # m = 1 n = 1
    basis[3] = 2 * x * y  # m = -2 n = 2
    basis[4] = 2 * x**2 + 2 * y**2 - 1  # m = 0 n = 2
    basis[5] = -1 * x**2 + y**2  # m = 2 n = 2
    basis[6] = -1 * x**3 + 3 * x * y**2  # m = -3 n = 3
    basis[7] = -2 * x + 3 * (x**3) + 3 * x * (y**2)  # m = -1 n = 3
    basis[8] = -2 * y + 3 * y**3 + 3 * (x**2) * y  # m = 1 n = 3
    basis[9] = y**3 - 3 * (x**2) * y  # m = 3 n =3
    basis[10] = -4 * (x**3) * y + 4 * x * (y**3)  # m = -4 n = 4
    basis[11] = -6 * x * y + 8 * (x**3) * y + 8 * x * (y**3)  # m = -2 n = 4
    basis[12] = (
        1 - 6 * x**2 - 6 * y**2 + 6 * x**4 + 12 * (x**2) * (y**2) + 6 * y**4
    )  # m = 0 n = 4
    basis[13] = 3 * x**2 - 3 * y**2 - 4 * x**4 + 4 * y**4  # m = 2 n = 4
    basis[14] = x**4 - 6 * (x**2) * (y**2) + y**4  # m = 4 n = 4
    basis[15] = x**5 - 10 * (x**3) * y**2 + 5 * x * (y**4)  # m = -5 n = 5
    basis[16] = (
        4 * x**3 - 12 * x * (y**2) - 5 * x**5 + 10 * (x**3) * (y**2) + 15 * x * y**4
    )  # m =-3 n = 5
    basis[17] = (
        3 * x
        - 12 * x**3
        - 12 * x * (y**2)
        + 10 * x**5
        + 20 * (x**3) * (y**2)
        + 10 * x * (y**4)
    )  # m= -1 n = 5
    basis[18] = (
        3 * y
        - 12 * y**3
        - 12 * y * (x**2)
        + 10 * y**5
        + 20 * (y**3) * (x**2)
        + 10 * y * (x**4)
    )  # m = 1 n = 5
    basis[19] = (
        -4 * y**3 + 12 * y * (x**2) + 5 * y**5 - 10 * (y**3) * (x**2) - 15 * y * x**4
    )  # m = 3 n = 5
    basis[20] = y**5 - 10 * (y**3) * x**2 + 5 * y * (x**4)  # m = 5 n = 5
    basis[21] = 6 * (x**5) * y - 20 * (x**3) * (y**3) + 6 * x * (y**5)  # m = -6 n = 6
    basis[22] = (
        20 * (x**3) * y - 20 * x * (y**3) - 24 * (x**5) * y + 24 * x * (y**5)
    )  # m = -4 n = 6
    basis[23] = (
        12 * x * y
        + 40 * (x**3) * y
        - 40 * x * (y**3)
        + 30 * (x**5) * y
        + 60 * (x**3) * (y**3)
        - 30 * x * (y**5)
    )  # m = -2 n = 6
    basis[24] = (
        -1
        + 12 * (x**2)
        + 12 * (y**2)
        - 30 * (x**4)
        - 60 * (x**2) * (y**2)
        - 30 * (y**4)
        + 20 * (x**6)
        + 60 * (x**4) * y**2
        + 60 * (x**2) * (y**4)
        + 20 * (y**6)
    )  # m = 0 n = 6
    basis[25] = (
        -6 * (x**2)
        + 6 * (y**2)
        + 20 * (x**4)
        - 20 * (y**4)
        - 15 * (x**6)
        - 15 * (x**4) * (y**2)
        + 15 * (x**2) * (y**4)
        + 15 * (y**6)
    )  # m = 2 n = 6
    basis[26] = (
        -5 * (x**4)
        + 30 * (x**2) * (y**2)
        - 5 * (y**4)
        + 6 * (x**6)
        - 30 * (x**4) * y**2
        - 30 * (x**2) * (y**4)
        + 6 * (y**6)
    )  # m = 4 n = 6
    basis[27] = (
        -1 * (x**6) + 15 * (x**4) * (y**2) - 15 * (x**2) * (y**4) + y**6
    )  # m = 6 n = 6
    basis[28] = (
        -1 * (x**7) + 21 * (x**5) * (y**2) - 35 * (x**3) * (y**4) + 7 * x * (y**6)
    )  # m = -7 n = 7
    basis[29] = (
        -6 * (x**5)
        + 60 * (x**3) * (y**2)
        - 30 * x * (y**4)
        + 7 * x**7
        - 63 * (x**5) * (y**2)
        - 35 * (x**3) * (y**4)
        + 35 * x * (y**6)
    )  # m = -5 n = 7
    basis[30] = (
        -10 * (x**3)
        + 30 * x * (y**2)
        + 30 * x**5
        - 60 * (x**3) * (y**2)
        - 90 * x * (y**4)
        - 21 * x**7
        + 21 * (x**5) * (y**2)
        + 105 * (x**3) * (y**4)
        + 63 * x * (y**6)
    )  # m =-3 n = 7
    basis[31] = (
        -4 * x
        + 30 * x**3
        + 30 * x * (y**2)
        - 60 * (x**5)
        - 120 * (x**3) * (y**2)
        - 60 * x * (y**4)
        + 35 * x**7
        + 105 * (x**5) * (y**2)
        + 105 * (x**3) * (y**4)
        + 35 * x * (y**6)
    )  # m = -1 n = 7
    basis[32] = (
        -4 * y
        + 30 * y**3
        + 30 * y * (x**2)
        - 60 * (y**5)
        - 120 * (y**3) * (x**2)
        - 60 * y * (x**4)
        + 35 * y**7
        + 105 * (y**5) * (x**2)
        + 105 * (y**3) * (x**4)
        + 35 * y * (x**6)
    )  # m = 1 n = 7
    basis[33] = (
        10 * (y**3)
        - 30 * y * (x**2)
        - 30 * y**5
        + 60 * (y**3) * (x**2)
        + 90 * y * (x**4)
        + 21 * y**7
        - 21 * (y**5) * (x**2)
        - 105 * (y**3) * (x**4)
        - 63 * y * (x**6)
    )  # m =3 n = 7
    basis[34] = (
        -6 * (y**5)
        + 60 * (y**3) * (x**2)
        - 30 * y * (x**4)
        + 7 * y**7
        - 63 * (y**5) * (x**2)
        - 35 * (y**3) * (x**4)
        + 35 * y * (x**6)
    )  # m = 5 n = 7
    basis[35] = (
        y**7 - 21 * (y**5) * (x**2) + 35 * (y**3) * (x**4) - 7 * y * (x**6)
    )  # m = 7 n = 7
    basis[36] = (
        -8 * (x**7) * y + 56 * (x**5) * (y**3) - 56 * (x**3) * (y**5) + 8 * x * (y**7)
    )  # m = -8 n = 8
    basis[37] = (
        -42 * (x**5) * y
        + 140 * (x**3) * (y**3)
        - 42 * x * (y**5)
        + 48 * (x**7) * y
        - 112 * (x**5) * (y**3)
        - 112 * (x**3) * (y**5)
        + 48 * x * (y**7)
    )  # m = -6 n = 8
    basis[38] = (
        -60 * (x**3) * y
        + 60 * x * (y**3)
        + 168 * (x**5) * y
        - 168 * x * (y**5)
        - 112 * (x**7) * y
        - 112 * (x**5) * (y**3)
        + 112 * (x**3) * (y**5)
        + 112 * x * (y**7)
    )  # m = -4 n = 8
    basis[39] = (
        -20 * x * y
        + 120 * (x**3) * y
        + 120 * x * (y**3)
        - 210 * (x**5) * y
        - 420 * (x**3) * (y**3)
        - 210 * x * (y**5)
        - 112 * (x**7) * y
        + 336 * (x**5) * (y**3)
        + 336 * (x**3) * (y**5)
        + 112 * x * (y**7)
    )  # m = -2 n = 8
    basis[40] = (
        1
        - 20 * x**2
        - 20 * y**2
        + 90 * x**4
        + 180 * (x**2) * (y**2)
        + 90 * y**4
        - 140 * x**6
        - 420 * (x**4) * (y**2)
        - 420 * (x**2) * (y**4)
        - 140 * (y**6)
        + 70 * x**8
        + 280 * (x**6) * (y**2)
        + 420 * (x**4) * (y**4)
        + 280 * (x**2) * (y**6)
        + 70 * y**8
    )  # m = 0 n = 8
    basis[41] = (
        10 * x**2
        - 10 * y**2
        - 60 * x**4
        + 105 * (x**4) * (y**2)
        - 105 * (x**2) * (y**4)
        + 60 * y**4
        + 105 * x**6
        - 105 * y**6
        - 56 * x**8
        - 112 * (x**6) * (y**2)
        + 112 * (x**2) * (y**6)
        + 56 * y**8
    )  # m = 2 n = 8
    basis[42] = (
        15 * x**4
        - 90 * (x**2) * (y**2)
        + 15 * y**4
        - 42 * x**6
        + 210 * (x**4) * (y**2)
        + 210 * (x**2) * (y**4)
        - 42 * y**6
        + 28 * x**8
        - 112 * (x**6) * (y**2)
        - 280 * (x**4) * (y**4)
        - 112 * (x**2) * (y**6)
        + 28 * y**8
    )  # m = 4 n = 8
    basis[43] = (
        7 * x**6
        - 105 * (x**4) * (y**2)
        + 105 * (x**2) * (y**4)
        - 7 * y**6
        - 8 * x**8
        + 112 * (x**6) * (y**2)
        - 112 * (x**2) * (y**6)
        + 8 * y**8
    )  # m = 6 n = 8
    basis[44] = (
        x**8 - 28 * (x**6) * (y**2) + 70 * (x**4) * (y**4) - 28 * (x**2) * (y**6) + y**8
    )  # m = 8 n = 9
    basis[45] = (
        x**9
        - 36 * (x**7) * (y**2)
        + 126 * (x**5) * (y**4)
        - 84 * (x**3) * (y**6)
        + 9 * x * (y**8)
    )  # m = -9 n = 9
    basis[46] = (
        8 * x**7
        - 168 * (x**5) * (y**2)
        + 280 * (x**3) * (y**4)
        - 56 * x * (y**6)
        - 9 * x**9
        + 180 * (x**7) * (y**2)
        - 126 * (x**5) * (y**4)
        - 252 * (x**3) * (y**6)
        + 63 * x * (y**8)
    )  # m = -7 n = 9
    basis[47] = (
        21 * x**5
        - 210 * (x**3) * (y**2)
        + 105 * x * (y**4)
        - 56 * x**7
        + 504 * (x**5) * (y**2)
        + 280 * (x**3) * (y**4)
        - 280 * x * (y**6)
        + 36 * x**9
        - 288 * (x**7) * (y**2)
        - 504 * (x**5) * (y**4)
        + 180 * x * (y**8)
    )  # m = -5 n = 9
    basis[48] = (
        20 * x**3
        - 60 * x * (y**2)
        - 105 * x**5
        + 210 * (x**3) * (y**2)
        + 315 * x * (y**4)
        + 168 * x**7
        - 168 * (x**5) * (y**2)
        - 840 * (x**3) * (y**4)
        - 504 * x * (y**6)
        - 84 * x**9
        + 504 * (x**5) * (y**4)
        + 672 * (x**3) * (y**6)
        + 252 * x * (y**8)
    )  # m = -3 n = 9
    basis[49] = (
        5 * x
        - 60 * x**3
        - 60 * x * (y**2)
        + 210 * x**5
        + 420 * (x**3) * (y**2)
        + 210 * x * (y**4)
        - 280 * x**7
        - 840 * (x**5) * (y**2)
        - 840 * (x**3) * (y**4)
        - 280 * x * (y**6)
        + 126 * x**9
        + 504 * (x**7) * (y**2)
        + 756 * (x**5) * (y**4)
        + 504 * (x**3) * (y**6)
        + 126 * x * (y**8)
    )  # m = -1 n = 9
    basis[50] = (
        5 * y
        - 60 * y**3
        - 60 * y * (x**2)
        + 210 * y**5
        + 420 * (y**3) * (x**2)
        + 210 * y * (x**4)
        - 280 * y**7
        - 840 * (y**5) * (x**2)
        - 840 * (y**3) * (x**4)
        - 280 * y * (x**6)
        + 126 * y**9
        + 504 * (y**7) * (x**2)
        + 756 * (y**5) * (x**4)
        + 504 * (y**3) * (x**6)
        + 126 * y * (x**8)
    )  # m = -1 n = 9
    basis[51] = (
        -20 * y**3
        + 60 * y * (x**2)
        + 105 * y**5
        - 210 * (y**3) * (x**2)
        - 315 * y * (x**4)
        - 168 * y**7
        + 168 * (y**5) * (x**2)
        + 840 * (y**3) * (x**4)
        + 504 * y * (x**6)
        + 84 * y**9
        - 504 * (y**5) * (x**4)
        - 672 * (y**3) * (x**6)
        - 252 * y * (x**8)
    )  # m = 3 n = 9
    basis[52] = (
        21 * y**5
        - 210 * (y**3) * (x**2)
        + 105 * y * (x**4)
        - 56 * y**7
        + 504 * (y**5) * (x**2)
        + 280 * (y**3) * (x**4)
        - 280 * y * (x**6)
        + 36 * y**9
        - 288 * (y**7) * (x**2)
        - 504 * (y**5) * (x**4)
        + 180 * y * (x**8)
    )  # m = 5 n = 9
    basis[53] = (
        -8 * y**7
        + 168 * (y**5) * (x**2)
        - 280 * (y**3) * (x**4)
        + 56 * y * (x**6)
        + 9 * y**9
        - 180 * (y**7) * (x**2)
        + 126 * (y**5) * (x**4)
        - 252 * (y**3) * (x**6)
        - 63 * y * (x**8)
    )  # m = 7 n = 9
    basis[54] = (
        y**9
        - 36 * (y**7) * (x**2)
        + 126 * (y**5) * (x**4)
        - 84 * (y**3) * (x**6)
        + 9 * y * (x**8)
    )  # m = 9 n = 9
    basis[55] = (
        10 * (x**9) * y
        - 120 * (x**7) * (y**3)
        + 252 * (x**5) * (y**5)
        - 120 * (x**3) * (y**7)
        + 10 * x * (y**9)
    )  # m = -10 n = 10
    basis[56] = (
        72 * (x**7) * y
        - 504 * (x**5) * (y**3)
        + 504 * (x**3) * (y**5)
        - 72 * x * (y**7)
        - 80 * (x**9) * y
        + 480 * (x**7) * (y**3)
        - 480 * (x**3) * (y**7)
        + 80 * x * (y**9)
    )  # m = -8 n = 10
    basis[57] = (
        270 * (x**9) * y
        - 360 * (x**7) * (y**3)
        - 1260 * (x**5) * (y**5)
        - 360 * (x**3) * (y**7)
        + 270 * x * (y**9)
        - 432 * (x**7) * y
        + 1008 * (x**5) * (y**3)
        + 1008 * (x**3) * (y**5)
        - 432 * x * (y**7)
        + 168 * (x**5) * y
        - 560 * (x**3) * (y**3)
        + 168 * x * (y**5)
    )  # m = -6 n = 10
    basis[58] = (
        140 * (x**3) * y
        - 140 * x * (y**3)
        - 672 * (x**5) * y
        + 672 * x * (y**5)
        + 1008 * (x**7) * y
        + 1008 * (x**5) * (y**3)
        - 1008 * (x**3) * (y**5)
        - 1008 * x * (y**7)
        - 480 * (x**9) * y
        - 960 * (x**7) * (y**3)
        + 960 * (x**3) * (y**7)
        + 480 * x * (y**9)
    )  # m = -4 n = 10
    basis[59] = (
        30 * x * y
        - 280 * (x**3) * y
        - 280 * x * (y**3)
        + 840 * (x**5) * y
        + 1680 * (x**3) * (y**3)
        + 840 * x * (y**5)
        - 1008 * (x**7) * y
        - 3024 * (x**5) * (y**3)
        - 3024 * (x**3) * (y**5)
        - 1008 * x * (y**7)
        + 420 * (x**9) * y
        + 1680 * (x**7) * (y**3)
        + 2520 * (x**5) * (y**5)
        + 1680 * (x**3) * (y**7)
        + 420 * x * (y**9)
    )  # m = -2 n = 10
    basis[60] = (
        -1
        + 30 * x**2
        + 30 * y**2
        - 210 * x**4
        - 420 * (x**2) * (y**2)
        - 210 * y**4
        + 560 * x**6
        + 1680 * (x**4) * (y**2)
        + 1680 * (x**2) * (y**4)
        + 560 * y**6
        - 630 * x**8
        - 2520 * (x**6) * (y**2)
        - 3780 * (x**4) * (y**4)
        - 2520 * (x**2) * (y**6)
        - 630 * y**8
        + 252 * x**10
        + 1260 * (x**8) * (y**2)
        + 2520 * (x**6) * (y**4)
        + 2520 * (x**4) * (y**6)
        + 1260 * (x**2) * (y**8)
        + 252 * y**10
    )  # m = 0 n = 10
    basis[61] = (
        -15 * x**2
        + 15 * y**2
        + 140 * x**4
        - 140 * y**4
        - 420 * x**6
        - 420 * (x**4) * (y**2)
        + 420 * (x**2) * (y**4)
        + 420 * y**6
        + 504 * x**8
        + 1008 * (x**6) * (y**2)
        - 1008 * (x**2) * (y**6)
        - 504 * y**8
        - 210 * x**10
        - 630 * (x**8) * (y**2)
        - 420 * (x**6) * (y**4)
        + 420 * (x**4) * (y**6)
        + 630 * (x**2) * (y**8)
        + 210 * y**10
    )  # m = 2 n = 10
    basis[62] = (
        -35 * x**4
        + 210 * (x**2) * (y**2)
        - 35 * y**4
        + 168 * x**6
        - 840 * (x**4) * (y**2)
        - 840 * (x**2) * (y**4)
        + 168 * y**6
        - 252 * x**8
        + 1008 * (x**6) * (y**2)
        + 2520 * (x**4) * (y**4)
        + 1008 * (x**2) * (y**6)
        - 252 * (y**8)
        + 120 * x**10
        - 360 * (x**8) * (y**2)
        - 1680 * (x**6) * (y**4)
        - 1680 * (x**4) * (y**6)
        - 360 * (x**2) * (y**8)
        + 120 * y**10
    )  # m = 4 n = 10
    basis[63] = (
        -28 * x**6
        + 420 * (x**4) * (y**2)
        - 420 * (x**2) * (y**4)
        + 28 * y**6
        + 72 * x**8
        - 1008 * (x**6) * (y**2)
        + 1008 * (x**2) * (y**6)
        - 72 * y**8
        - 45 * x**10
        + 585 * (x**8) * (y**2)
        + 630 * (x**6) * (y**4)
        - 630 * (x**4) * (y**6)
        - 585 * (x**2) * (y**8)
        + 45 * y**10
    )  # m = 6 n = 10
    basis[64] = (
        -9 * x**8
        + 252 * (x**6) * (y**2)
        - 630 * (x**4) * (y**4)
        + 252 * (x**2) * (y**6)
        - 9 * y**8
        + 10 * x**10
        - 270 * (x**8) * (y**2)
        + 420 * (x**6) * (y**4)
        + 420 * (x**4) * (y**6)
        - 270 * (x**2) * (y**8)
        + 10 * y**10
    )  # m = 8 n = 10
    basis[65] = (
        -1 * x**10
        + 45 * (x**8) * (y**2)
        - 210 * (x**6) * (y**4)
        + 210 * (x**4) * (y**6)
        - 45 * (x**2) * (y**8)
        + y**10
    )  # m = 10 n = 10
    return basis


def zernike_surface(
    coefficients: np.ndarray, x: np.ndarray, y: np.ndarray
) -> np.ndarray:
    """Weighted sum ``sum_i c_i P_i(x, y)`` of the Zernike basis.

    Parameters
    ----------
    coefficients : np.ndarray, [n_coefficients <= 66]
        Real or complex coefficients; missing trailing terms are treated as zero.
    x, y : np.ndarray
        Aperture coordinates normalised to the dish radius.

    Returns
    -------
    np.ndarray, x.shape
        Complex if ``coefficients`` is complex.
    """
    coefficients = np.asarray(coefficients)
    if coefficients.shape[0] > N_ZERNIKE_TERMS:
        raise ValueError(
            f"At most {N_ZERNIKE_TERMS} Zernike coefficients are supported."
        )
    basis = zernike_basis(x, y)[: coefficients.shape[0]]
    return np.tensordot(coefficients, basis, axes=(0, 0))
